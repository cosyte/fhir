#!/usr/bin/env tsx
/**
 * Capture what a BASE tree outputs for every document of the output-equivalence corpus, as one
 * SHA-256 per document, committed as expectation data.
 *
 *     pnpm capture:output-digests                 # against origin/main
 *     pnpm capture:output-digests --base <ref>    # against any ref
 *
 * The corpus and the record of one document live in `test/_output-corpus.ts`, shared with
 * `test/output-equivalence.test.ts`, which recomputes each digest on head and requires it to be
 * identical. That is the evidence a change meant to make the read, the validator or the writers
 * faster changed no parse result, issue, warning, error or written output.
 *
 * The documents are generated with head's own corpus code and only the tree under test comes from
 * the base ref, so both sides read exactly the same text. `git archive` is used rather than a
 * worktree so the materialized tree cannot pick up an untracked file from the working tree. Re-run
 * it at the same base and the file must come back byte-identical.
 *
 * @packageDocumentation
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { digestOf, outputCorpus, recordOf, type OutputApi } from "../test/_output-corpus.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");
const OUT = join(REPO, "test", "__data__", "output-digests.json");

/** The ref to capture, `--base <ref>` or `origin/main`. */
function baseRef(argv: readonly string[]): string {
  const at = argv.indexOf("--base");
  return at === -1 ? "origin/main" : (argv[at + 1] ?? "origin/main");
}

/** Materialize `src/` at `ref` into a temp directory and import it. */
async function loadBase(ref: string): Promise<{ api: OutputApi; dir: string }> {
  const dir = mkdtempSync(join(tmpdir(), "fhir-output-digests-"));
  const archive = execFileSync("git", ["archive", ref, "src"], {
    cwd: REPO,
    maxBuffer: 256 * 1024 * 1024,
    encoding: "buffer",
  });
  execFileSync("tar", ["-x", "-C", dir], { input: archive });
  const api = (await import(pathToFileURL(join(dir, "src", "index.ts")).href)) as OutputApi;
  return { api, dir };
}

async function main(): Promise<void> {
  const ref = baseRef(process.argv.slice(2));
  const sha = execFileSync("git", ["rev-parse", ref], { cwd: REPO, encoding: "utf8" }).trim();
  const { api, dir } = await loadBase(ref);
  try {
    const documents: Record<string, string> = {};
    for (const doc of outputCorpus()) {
      if (doc.name in documents) throw new Error(`two corpus documents are named ${doc.name}`);
      documents[doc.name] = digestOf(recordOf(api, doc));
    }
    const payload = {
      note: "Generated by scripts/capture-output-digests.ts. Do not hand-edit: re-run it instead.",
      base: sha,
      documents,
    };
    writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
    console.log(`captured ${String(Object.keys(documents).length)} digests at ${sha} -> ${OUT}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

await main();
